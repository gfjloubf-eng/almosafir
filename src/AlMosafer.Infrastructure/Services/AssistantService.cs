using System.Text;
using AlMosafer.Application.DTOs.Assistant;
using AlMosafer.Application.Interfaces;

namespace AlMosafer.Infrastructure.Services;

/// <summary>
/// محرك «مساعد المسافر» القاعدي (P54): يجيب بالعربية فوراً وبلا أي مفتاح خارجي.
/// — يطبّع النص (ألف/همزة/تاء مربوطة/تشكيل) ليتعرف النوايا بثبات.
/// — واعٍ بالبيانات الحية: عند سؤال «كم رحلة متاحة؟» يجيب من قاعدة البيانات فعلياً
///   (عبر IReportingService + ILineService) لا من نص ثابت.
/// — معمارياً جاهز للترقية: الواجهة IAssistantService واحدة، فيمكن استبدال هذا
///   المحرك بمزوّد LLM (OpenAI/Gemini) متى توفر مفتاح — دون لمس المتحكم أو الواجهة.
/// </summary>
public class AssistantService : IAssistantService
{
    private readonly IReportingService _reporting;
    private readonly ILineService _lines;

    public AssistantService(IReportingService reporting, ILineService lines)
    {
        _reporting = reporting;
        _lines = lines;
    }

    private static readonly string[] DefaultChips =
    {
        "كيف أحجز رحلة؟",
        "كم رحلة متاحة الآن؟",
        "طرق الدفع",
        "كيف أتواصل مع السائق؟"
    };

    public async Task<AssistantReplyDto> AskAsync(string message)
    {
        var q = Normalize(message);

        if (string.IsNullOrWhiteSpace(q))
        {
            return Reply("اكتب سؤالك وسأجيبك فوراً 🚀", DefaultChips);
        }

        // ─── التحية ───
        if (Any(q, "مرحبا", "اهلا", "السلام", "صباح", "مساء", "هاي", "هلا", "كيفك", "وش اخبار"))
        {
            return Reply(
                "أهلاً بك في منصة المسافر 👋\nأنا مساعدك الذكي، جاهز أجيبك عن أي سؤال يتعلق بالحجز والدفع والرحلات.\nاكتب سؤالك أو اختر من الاقتراحات بالأسفل.",
                DefaultChips);
        }

        // ─── الهوية ───
        if (Any(q, "من انت", "مين انت", "وش انت", "ما انت", "تعرف عن نفسك"))
        {
            return Reply(
                "أنا «مساعد المسافر» 🤖 — مساعد ذكي مدمج في المنصة.\nأفهم أسئلتك بالعربية وأجيبك فوراً، وأقرأ بعض البيانات الحية (مثل عدد الرحلات المتاحة الآن) من قاعدة البيانات مباشرة.\nوأستطيع أيضاً أن أقرأ إجاباتي بصوتٍ مسموع 🔊 — جرّب زر السماعة بجانب ردي.",
