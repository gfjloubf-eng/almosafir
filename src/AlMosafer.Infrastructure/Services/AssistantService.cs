                new[] { "طرق الدفع", "كيف أتواصل مع السائق؟", "كم رحلة متاحة الآن؟" });
        }

        // ─── الدفع ───
        if (Any(q, "دفع", "ادفع", "سعر", "تكلفه", "ريال", "نقد", "كاش", "محفظه", "خصم", "رسوم"))
        {
            return Reply(
                "نظام الدفع في المنصة مرن ويناسب واقعنا اليمني 💵\n• «نقداً عند الركوب»: تدفع للسائق مباشرة عند اللقاء — الخيار الأنسب لاقتصادنا النقدي.\n• «دفع تجريبي فوري»: محاكاة دفع إلكتروني للتجربة (بلا خصم حقيقي).\n\nالمحافظ الرقمية الحقيقية (محفظتي/ون كاش) قادمة في المرحلة التالية — البنية جاهزة لها.",
                new[] { "كيف أحجز رحلة؟", "هل بياناتي محمية؟" });
        }

        // ─── التواصل مع السائق ───
        if (Any(q, "سائق", "اتصال", "تواصل", "واتساب", "هاتف", "رقم", "كلم"))
        {
            return Reply(
                "التواصل مع السائق مباشر وآمن 📞\nبعد تأكيد حجزك يظهر لك رقم هاتف السائق، ويمكنك مراسلته فوراً عبر «المحادثات» داخل المنصة (دردشة لحظية بلا كشف رقمك للعامة).\n\nرقم السائق يُخفى قبل الحجز حفاظاً على خصوصيته.",
                new[] { "كيف أحجز رحلة؟", "كيف ألغي حجزي؟" });
