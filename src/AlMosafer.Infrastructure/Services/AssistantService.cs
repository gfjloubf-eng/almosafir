    private async Task<AssistantReplyDto> LiveStatsAsync()
    {
        try
        {
            var stats = await _reporting.GetPublicStatsAsync();
            var cities = await _lines.GetActiveCitiesAsync();
            return Reply(
                $"المنصة تعمل الآن بنشاط 🚀\n" +
                $"• رحلات متاحة الآن: {stats.ActiveTrips}\n" +
                $"• سائقون معتمدون: {stats.DriversCount}\n" +
                $"• حجوزات منجزة: {stats.CompletedBookings}\n" +
                $"• مدن مغطاة بخطوط داخلية: {cities.Count}\n\nهذه أرقام حية تُقرأ من قاعدة البيانات لحظة سؤالك.",
                new[] { "كيف أحجز رحلة؟", "طرق الدفع", "شبكة الخطوط" });
        }
        catch
        {
            // أفضل جهد: إن تعذّر قراءة الحي، نعتذر بأدب ولا نكسر المساعد
            return Reply(
                "تعذّرت قراءة الأرقام الحية الآن (قد تكون قاعدة البيانات مشغولة). جرّب بعد لحظات، أو اسألني عن شيء آخر.",
                DefaultChips);
        }
    }

    private static AssistantReplyDto Reply(string answer, IEnumerable<string> suggestions)
    {
        return new AssistantReplyDto
        {
            Answer = answer,
            Suggestions = suggestions.ToList()
        };
    }

    private static bool Any(string q, params string[] tokens)
        => tokens.Any(t => q.Contains(t, StringComparison.Ordinal));

    private static string Normalize(string text)
    {
        if (string.IsNullOrWhiteSpace(text)) return string.Empty;

        var sb = new StringBuilder(text.Length);
        foreach (var ch in text.Trim())
        {
            switch (ch)
            {
                case 'أ': case 'إ': case 'آ': case 'ا': sb.Append('ا'); break;
                case 'ى': sb.Append('ي'); break;
                case 'ة': sb.Append('ه'); break;
                case 'ؤ': sb.Append('و'); break;
                case 'ئ': sb.Append('ي'); break;
                case '؟': case '?': sb.Append(' '); break;
                default:
                    if (char.IsLetterOrDigit(ch) || char.IsWhiteSpace(ch))
                        sb.Append(char.ToLowerInvariant(ch));
                    else
                        sb.Append(' ');
                    break;
            }
        }

        // ضغط الفراغات المتكررة
        var normalized = sb.ToString();
        while (normalized.Contains("  ", StringComparison.Ordinal))
            normalized = normalized.Replace("  ", " ", StringComparison.Ordinal);
        return normalized.Trim();
    }
}
